function passeio(
  base: Omit<Passeio, 'distanciaKm' | 'pontos' | 'rotaNome'> & { rota: Rota },
): Passeio {
  const { rota, ...resto } = base;
  return {
    ...resto,
    rotaNome: rota.nome,
    pontos: rota.pontos,
    distanciaKm: distanciaTrajeto(rota.pontos),
  };
}

