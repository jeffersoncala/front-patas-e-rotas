const MINUTO = 60_000;
const DIA = 24 * 60 * MINUTO;

/** Data em ISO deslocada a partir de agora, para os exemplos parecerem sempre recentes. */
function aPartirDeAgora(ms: number, hora?: number, minuto = 0): string {
  const data = new Date(Date.now() + ms);
  if (hora !== undefined) {
    data.setHours(hora, minuto, 0, 0);
  }
  return data.toISOString();
}

